#!/usr/bin/env node
/* =============================================================================
   Construit app/aide.html à partir de docs/manuel.md (et aide.en.html de manuel.en.md).
   -----------------------------------------------------------------------------
   Le manuel vit en Markdown dans docs/, lisible sur GitHub ; l'application en
   sert une copie HTML, dans son propre style, consultable hors ligne. Un petit
   convertisseur suffit : titres, paragraphes, listes, tableaux, citations,
   blocs de code, gras, italique, code en ligne, liens. Pas de dépendance.

     node construire-aide.js             # écrit app/aide.html
     node construire-aide.js --verifier  # échoue si app/aide.html n'est pas à jour
   ============================================================================= */

const fs = require('fs');
const path = require('path');

// Une page par langue : le manuel français est la référence, l'anglais sa
// traduction, chacun génère sa page d'aide.
const PAGES = [
  { source: path.join(__dirname, '..', 'docs', 'manuel.md'), sortie: path.join(__dirname, '..', 'app', 'aide.html'), langue: 'fr',
    titre: 'Aide', description: 'Manuel du socle chauffant : installation, réglages, alertes, entretien, dépannage.',
    retour: '← Application', pied: ['Application', 'Flasher un socle', 'Mentions légales', 'Confidentialité', 'Fiche à imprimer'],
    autre: '<a href="aide.en.html" lang="en">English</a>', legales: ['mentions-legales.html', 'confidentialite.html'],
    genere: 'Généré depuis docs/manuel.md — ne pas modifier ce fichier à la main.' },
  { source: path.join(__dirname, '..', 'docs', 'manuel.en.md'), sortie: path.join(__dirname, '..', 'app', 'aide.en.html'), langue: 'en',
    titre: 'Help', description: 'Heating base manual: installation, settings, alerts, maintenance, troubleshooting.',
    retour: '← App', pied: ['App', 'Flash a base', 'Legal notice', 'Privacy', 'Printable sheet'],
    autre: '<a href="aide.html" lang="fr">Français</a>', legales: ['mentions-legales.en.html', 'confidentialite.en.html'],
    genere: 'Generated from docs/manuel.en.md — do not edit this file by hand.' }
];

const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// Mise en forme à l'intérieur d'une ligne. Le code en ligne est protégé en
// premier : rien ne doit être interprété dedans.
function enLigne(texte) {
  const codes = [];
  const marque = String.fromCharCode(0);
  let s = esc(texte).replace(/`([^`]+)`/g, (m, c) => { codes.push(c); return `${marque}${codes.length - 1}${marque}`; });
  s = s.replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>')
       .replace(/(^|[^*])\*([^*]+)\*/g, '$1<em>$2</em>')
       .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (m, t, u) => {
         const externe = /^https?:/.test(u);
         // Les liens vers le dépôt (docs/…, README) pointent vers GitHub.
         const cible = externe ? u : 'https://github.com/NoeMrct/terrarium_thermostat/blob/main/' + u;
         return `<a href="${esc(cible)}"${externe ? ' rel="noopener"' : ''}>${t}</a>`;
       })
       .replace(/`docs\/([^`]+)`/g, '`docs/$1`');
  return s.replace(new RegExp(marque + '(\\d+)' + marque, 'g'), (m, i) => `<code>${codes[+i]}</code>`);
}

const ancre = t => t.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '')
  .replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

function convertir(md) {
  const lignes = md.split('\n');
  const html = [];
  const sommaire = [];
  let i = 0;
  const bloc = () => lignes[i] === undefined ? null : lignes[i];
  while (i < lignes.length) {
    const l = lignes[i];
    if (/^\s*$/.test(l)) { i++; continue; }
    let m;
    if ((m = /^(#{1,3}) (.+)$/.exec(l))) {
      const niveau = m[1].length, titre = m[2].trim();
      if (niveau === 1) html.push(`<h1>${enLigne(titre)}</h1>`);
      else {
        const id = ancre(titre);
        if (niveau === 2) sommaire.push({ id, titre });
        html.push(`<h${niveau} id="${id}">${enLigne(titre)}</h${niveau}>`);
      }
      i++; continue;
    }
    if (/^```/.test(l)) {
      const code = [];
      i++;
      while (i < lignes.length && !/^```/.test(lignes[i])) code.push(lignes[i++]);
      i++;
      html.push(`<pre><code>${esc(code.join('\n'))}</code></pre>`);
      continue;
    }
    if (/^>/.test(l)) {
      const q = [];
      while (i < lignes.length && /^>/.test(lignes[i])) q.push(lignes[i++].replace(/^>\s?/, ''));
      html.push(`<blockquote><p>${enLigne(q.join(' '))}</p></blockquote>`);
      continue;
    }
    if (/^\|/.test(l)) {
      const rangs = [];
      while (i < lignes.length && /^\|/.test(lignes[i])) rangs.push(lignes[i++]);
      const cellules = r => r.replace(/^\||\|$/g, '').split('|').map(c => c.trim());
      const tete = cellules(rangs[0]);
      const corps = rangs.slice(2).map(cellules);
      html.push(`<table><thead><tr>${tete.map(c => `<th>${enLigne(c)}</th>`).join('')}</tr></thead><tbody>${
        corps.map(r => `<tr>${r.map(c => `<td>${enLigne(c)}</td>`).join('')}</tr>`).join('')}</tbody></table>`);
      continue;
    }
    if (/^(-|\d+\.) /.test(l)) {
      const ordonnee = /^\d+\./.test(l);
      const items = [];
      while (i < lignes.length && (/^(-|\d+\.) /.test(lignes[i]) || /^\s{2,}\S/.test(lignes[i]))) {
        if (/^(-|\d+\.) /.test(lignes[i])) items.push(lignes[i].replace(/^(-|\d+\.) /, ''));
        else items[items.length - 1] += ' ' + lignes[i].trim();
        i++;
      }
      html.push(`<${ordonnee ? 'ol' : 'ul'}>${items.map(x => `<li>${enLigne(x)}</li>`).join('')}</${ordonnee ? 'ol' : 'ul'}>`);
      continue;
    }
    // Paragraphe : jusqu'à la prochaine ligne vide ou le prochain bloc.
    const p = [];
    while (i < lignes.length && !/^\s*$/.test(lignes[i]) && !/^(#{1,3} |```|>|\||- |\d+\. )/.test(lignes[i])) p.push(lignes[i++].trim());
    html.push(`<p>${enLigne(p.join(' '))}</p>`);
    void bloc;
  }
  return { corps: html.join('\n'), sommaire };
}

function page(md, p) {
  const { corps, sommaire } = convertir(md);
  const titre = (/^# (.+)$/m.exec(md) || [null, p.titre])[1];
  const toc = `<ol class="sommaire">${sommaire.map(s => `<li><a href="#${s.id}">${enLigne(s.titre)}</a></li>`).join('')}</ol>`;
  return `<!doctype html>
<html lang="${p.langue}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="color-scheme" content="light dark">
<title>${esc(titre)}</title>
<meta name="description" content="${esc(p.description)}">
<link rel="icon" href="icone.svg">
<meta name="theme-color" content="#f3f5f7" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#0f1115" media="(prefers-color-scheme: dark)">
<meta http-equiv="Content-Security-Policy" content="default-src 'self'; img-src 'self' data:; style-src 'self'; script-src 'none'; base-uri 'self'">
<link rel="stylesheet" href="style.css">
</head>
<body data-vue="page">
<header id="entete">
  <h1>${p.titre}</h1>
  <a class="btn btn-fantome btn-petit" href="index.html">${p.retour}</a>
</header>
<main class="page">
<article class="carte prose">
${corps.replace('</h1>', '</h1>\n' + toc)}
<p class="discret">${p.genere}</p>
</article>
<footer class="pied colonne">
  <div class="pied-ligne liens">
    <a href="index.html">${p.pied[0]}</a>
    <a href="installer.html">${p.pied[1]}</a>
    <a href="${p.legales[0]}">${p.pied[2]}</a>
    <a href="${p.legales[1]}">${p.pied[3]}</a>
    <a href="demarrage-rapide.html">${p.pied[4]}</a>
    ${p.autre}
  </div>
</footer>
</main>
</body>
</html>
`;
}

for (const p of PAGES) {
  const html = page(fs.readFileSync(p.source, 'utf8'), p);
  const nom = path.relative(path.join(__dirname, '..'), p.sortie);
  if (process.argv.includes('--verifier')) {
    const actuel = fs.existsSync(p.sortie) ? fs.readFileSync(p.sortie, 'utf8') : '';
    if (actuel !== html) { console.error(`${nom} n'est pas à jour : lancer node outils/construire-aide.js`); process.exit(1); }
    console.log(`${nom} à jour`);
  } else {
    fs.writeFileSync(p.sortie, html);
    console.log(`${nom} écrit (${(html.length / 1024).toFixed(1)} Ko)`);
  }
}
